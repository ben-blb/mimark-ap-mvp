interface InvoiceOpts {
  supplier: SupplierKey;
  oc: string | null;
  subtotal: number;
  folio: string;
  over?: Partial<InvoiceDoc>;
}
const FECHA = '2026-11-10';
function invoiceDoc(o: InvoiceOpts): InvoiceDoc {
  const s = SUPPLIERS[o.supplier];
  return {
    kind: 'FACTURA',
    layout: 0,
    emisor: s.name,
    rfc: s.taxId,
    folio: o.folio,
    uuid: randomUUID().toUpperCase(),
    fecha: FECHA,
    oc: o.oc,
    moneda: 'MXN',
    ...amounts(o.subtotal),
    ...o.over,
  };
}


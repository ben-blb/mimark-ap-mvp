export interface OcLine {
  product: string;
  cases: number;
  unitCost: number;
  deposit?: number;
  /** Importe impreso si no debe coincidir con cajas × costo + depósito (caso de aviso). */
  printedTotal?: number;
}
export interface OcDoc {
  number: string;
  /** MM-DD-AAAA, como ParLevel. */
  date: string;
  /** Texto del bloque «To:». */
  to: string;
  lines: OcLine[];
}

export const r2 = (n: number) => Math.round(n * 100) / 100;
export const fmt = (n: number) =>
  `$${n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
export const lineTotal = (l: OcLine) =>
  l.printedTotal ?? r2(l.cases * l.unitCost + (l.deposit ?? 0));
export const ocSubtotal = (oc: OcDoc) => r2(oc.lines.reduce((sum, l) => sum + lineTotal(l), 0));

/** OC con el diseño de ParLevel Warehouse (spec 015): folio «Order #P…», fecha MM-DD-AAAA, From/To y subtotal estimado. */
export async function renderOcPdf(oc: OcDoc): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([612, 792]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const text = (t: string, x: number, y: number, size = 9, b = false) =>
    page.drawText(t, { x, y, size, font: b ? bold : font, color: rgb(0, 0, 0) });

  text('SMART KIOSKO', 40, 750, 16, true);
  text(`Order #${oc.number}`, 40, 728, 12, true);
  text(`Order Date: ${oc.date}`, 40, 712);
  text('From:', 40, 686, 9, true);
  ['SMART KIOSKO', 'calle de prueba 100', 'colonia ejemplo', 'Monterrey, MX-NLE  64890'].forEach(
    (t, i) => text(t, 40, 673 - i * 12),
  );
  text('To:', 330, 686, 9, true);
  [oc.to, 'Monterrey', 'Monterrey, Nuevo Leon  64890'].forEach((t, i) =>
    text(t, 330, 673 - i * 12),
  );

  const cols = [40, 90, 250, 300, 345, 400, 450, 505, 555];
  const head = [
    'Cst ID',
    'Product',
    'Cases Ord.',
    'Cases Rec.',
    'Date Code',
    'Unit Cost',
    'Deposit',
    'Order Total',
    'Rec. Total',
  ];
  let y = 600;
  head.forEach((h, i) => text(h, cols[i]!, y, 7, true));
  y -= 18;
  oc.lines.forEach((l, i) => {
    const row = [
      String(1000 + i),
      l.product,
      String(l.cases),
      '0',
      '',
      fmt(l.unitCost),
      fmt(l.deposit ?? 0),
      fmt(lineTotal(l)),
      '$0.00',
    ];
    row.forEach((c, j) => text(c, cols[j]!, y, 8));
    y -= 16;
  });
  y -= 14;
  text(`Est. Subtotal: ${fmt(ocSubtotal(oc))}`, 400, y, 10, true);
  text('Generated by Parlevel Warehouse.', 40, 40, 7);
  text('Documento sintético de prueba.', 40, 28, 7);
  return pdf.save();
}


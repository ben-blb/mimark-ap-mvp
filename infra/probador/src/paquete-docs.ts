export const ocDoc = (number: string): OcDoc => {
  const o = OCS[number]!;
  return {
    number,
    date: o.date,
    to: o.supplier === 'comprador' ? 'SMART KIOSKO' : SUPPLIERS[o.supplier].alias.toUpperCase(),
    lines: o.lines,
  };
};

export interface InvoiceOpts {
  supplier: SupplierKey;
  oc: string | null;
  subtotal: number;
  folio: string;
  over?: Partial<InvoiceDoc>;
}
export const FECHA = '2026-11-10';
export function invoiceDoc(o: InvoiceOpts): InvoiceDoc {
  const s = SUPPLIERS[o.supplier];
  return {
    kind: 'FACTURA',
    layout: 0,
    emisor: s.name,
    rfc: s.taxId,
    folio: o.folio,
    uuid: randomUUID().toUpperCase(),
    fecha: FECHA,
    oc: o.oc,
    moneda: 'MXN',
    ...amounts(o.subtotal),
    ...o.over,
  };
}

